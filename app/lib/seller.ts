/*
 * Продавець — дані, які Закон «Про електронну комерцію» (ст. 7) вимагає
 * показати покупцю: повне найменування або ПІБ, код, адреса, контакти.
 *
 * Поки SELLER = null, сторінка /offer відповідає 404, а реквізитів і
 * посилання на оферту на сайті немає — вигаданих даних покупець не побачить.
 * Щойно власник надішле реквізити, заповніть SELLER — і все з'явиться само:
 * блок реквізитів у футері, сторінка оферти, посилання при оформленні.
 */

export type Seller = {
  /** fop — фізична особа-підприємець, tov — ТОВ */
  kind: "fop" | "tov";
  /** ФОП — ПІБ повністю: «Іваненко Ірина Петрівна»; ТОВ — повна назва: «ТОВ "Фемілі Кемпінг"» */
  name: string;
  /** ФОП — РНОКПП (10 цифр); ТОВ — код ЄДРПОУ (8 цифр) */
  code: string;
  /** Місцезнаходження (адреса реєстрації) */
  address: string;
  /** Рахунок для «Оплати на рахунок» — необов'язково */
  iban?: string;
  bank?: string;
};

export const SELLER: Seller | null = null;

/** «ФОП Іваненко Ірина Петрівна» або назва ТОВ */
export const sellerTitle = (s: Seller) => (s.kind === "fop" ? `ФОП ${s.name}` : s.name);

/** Підпис коду: РНОКПП для ФОП, ЄДРПОУ для ТОВ */
export const sellerCodeLabel = (s: Seller) => (s.kind === "fop" ? "РНОКПП" : "Код ЄДРПОУ");

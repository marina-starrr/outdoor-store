import type { CategorySlug } from "../components/catalog-data";

/*
 * Підказки, у яку нашу категорію потрапляють товари з категорії постачальника.
 * Власник бачить їх у адмінці й може змінити; тут — лише значення за замовчуванням.
 *
 * Категорія постачальника приходить шляхом від кореня: «Намети > Naturehike намети > Двомісні».
 * Спершу — те, що магазину сімейного кемпінгу не потрібно (на будь-якому рівні),
 * далі правила перевіряються від найглибшого рівня до кореня: «Двомісні» нічого
 * не каже, а «Naturehike намети» — так
 */

/** «Категорію визначати за назвою кожного товару» — для змішаних категорій постачальника */
export const AUTO_CATEGORY = "auto";
export type MappedCategory = CategorySlug | typeof AUTO_CATEGORY | "";

/** Роздільник рівнів у назві категорії з шляхом */
export const PATH_SEPARATOR = " > ";

/*
 * Не для нашого магазину: ножі й точила (окрема ніша, частину ножів можуть визнати
 * холодною зброєю), засоби самооборони, мастила, садова й електротехніка,
 * батарейки/зарядки та кріплення для ліхтарів, вело- й промислові ліхтарі
 */
const SKIP_LEVEL = /(?<!\p{L})(нож|ніж)|точил|перцев|балончик|мастил|^масла|^техніка$|електроінструмент|садов\p{L}* інструмент|живлення|велофар|індустріальн/iu;
// «Ліхтарі > Fenix аксесуари», «Тактичне спорядження > Nextorch аксесуари» (кріплення на зброю)
const SKIP_PATH = /(ліхтар|тактичн)[^>]* > (?:[^>]* > )*[^>]*аксесуар|аксесуар\p{L}* для ліхтар/iu;

const RULES: [RegExp, CategorySlug][] = [
  // Ліхтарі — раніше за «тактичне» («Тактичні ліхтарі») і «газ» («Газові лампи»)
  [/ліхтар|освітл|ламп/iu, "lighting"],
  [/військ|тактич|армій/iu, "tactical"],
  [/риба|рибол|вудк|короп/iu, "fishing"],
  // «Акумулятори холоду» — пікнік, тож раніше за електроніку
  [/пікнік|термосум|холодильн|акумулятор\p{L}* холоду/iu, "picnic"],
  // «Рації», але не «матраци»
  [/(?<!\p{L})рац|генерат|кондиц|камер|електрон|павербанк|повербанк|power|зарядн\p{L}* станц|сонячн\p{L}* панел/iu, "electronics"],
  [/термос|термокух|термочаш/iu, "thermos"],
  [/термобіл|одяг|шкарпет|взутт|рукавич|рукавиц|шапк|дощовик/iu, "clothing"],
  // «Гойдалки, тенти, гамаки» — гамаки, тож раніше за «намети»
  [/гамак|гойдалк/iu, "hammocks"],
  [/намет|тент|парасол/iu, "tents"],
  [/рюкзак|чохл|гермомі|сумк|багаж/iu, "backpacks"],
  [/спальн|каремат|килим|коврик|матрац|подушк/iu, "sleeping-bags"],
  [/обігрівач/iu, "accessories"],
  [/газ|пальник|посуд|казан|кавовар/iu, "cookware"],
  [/крісл|стіл|стол|стільц|ліжк|шезлонг|розкладач|меблі/iu, "furniture"],
  [/мангал|гриль|барбек/iu, "grills"],
  [/аксес|туризм|туристичн|мультитул|лопат|сокир|інструмент|комах|іграшк/iu, "accessories"],
];

/** Підказка: наша категорія за назвою (шляхом) їхньої ("" — не імпортувати) */
export function suggestCategory(name: string, supplierName?: string): MappedCategory {
  // Категорія з назвою самого постачальника («Ranger») — збірна, там усе підряд
  if (supplierName && name.trim().toLowerCase() === supplierName.trim().toLowerCase()) return AUTO_CATEGORY;
  const levels = name.split(PATH_SEPARATOR).map((s) => s.trim()).filter(Boolean);
  if (levels.some((l) => SKIP_LEVEL.test(l)) || SKIP_PATH.test(name)) return "";
  for (const level of [...levels].reverse()) {
    const hit = RULES.find(([re]) => re.test(level));
    if (hit) return hit[1];
  }
  return "";
}

/*
 * Наша категорія за назвою ТОВАРУ (для збірних категорій постачальника).
 * Порядок важливий: «коропова розкладачка» — меблі, а не рибалка;
 * «чохол для вудилища» — рибалка, а не рюкзаки
 */
const PRODUCT_RULES: [RegExp, CategorySlug][] = [
  [/power ?bank|павербанк|(?<!\p{L})раці[яї]|генератор|кондиціонер|підводн\p{L}* камер/iu, "electronics"],
  [/плитоноск|підсумок|кобур|розвантаж|кавер|шолом|бронежилет|балаклав|тактичн|військов|турнікет|(?<!\p{L})ак(?!\p{L})|мульт[иі]кам|піксел/iu, "tactical"],
  [/термосумк|холодильник|пікнік|акумулятор холоду/iu, "picnic"],
  [/термос|термокру|термокух|термочаш/iu, "thermos"],
  [/термобілизн|шкарпет|кофт|футболк|штан|шорт/iu, "clothing"],
  [/гамак|гойдалк|павільйон/iu, "hammocks"],
  [/кр[іi]сл|(?<!\p{L})стіл|стіл[еє]ць|стільц|ліжк|розкладачк|шезлонг/iu, "furniture"],
  [/вудк|вудилищ|котушк|[сc]пінінг|сигналізатор|род-под|буз-бар|підставка телескоп|короп|фідер|приманк|гачк|волосін|блешн|воблер/iu, "fishing"],
  [/намет|тент|bivvy/iu, "tents"],
  [/рюкзак|гермомі|чохол/iu, "backpacks"],
  [/спальн|карема|карима|килимок/iu, "sleeping-bags"],
  [/пальник|казан|посуд|чайник|сковор|каструл/iu, "cookware"],
  [/ліхтар|лампа/iu, "lighting"],
  [/мангал|гриль|барбек/iu, "grills"],
];

/** Категорія за назвою товару; undefined — не впізнали (товар не імпортується) */
export function categoryFromName(name: string): CategorySlug | undefined {
  return PRODUCT_RULES.find(([re]) => re.test(name))?.[1];
}

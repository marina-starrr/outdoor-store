/** Детермінований генератор — однакові відгуки на сервері й у браузері */
function seeded(seed: string) {
  let h = 2166136261;
  for (const ch of seed) h = Math.imul(h ^ ch.charCodeAt(0), 16777619);
  return () => {
    h = Math.imul(h ^ (h >>> 15), 2246822507);
    h = Math.imul(h ^ (h >>> 13), 3266489909);
    return ((h ^= h >>> 16) >>> 0) / 4294967296;
  };
}

const months = ["січня", "лютого", "березня", "квітня", "травня", "червня", "липня", "серпня", "вересня", "жовтня", "листопада", "грудня"];

export function productReviews(p: Product): Review[] {
  const rand = seeded(p.id);
  const pool = [...(reviewTexts[p.category] ?? []), ...commonReviews];
  const count = Math.min(p.reviews, 8);
  // День відліку фіксований, щоб не залежати від часу рендеру
  let day = 300 - Math.floor(rand() * 10);
  return Array.from({ length: count }, (_, i) => {
    const [author, city] = authors[Math.floor(rand() * authors.length)];
    const text = pool[(i + Math.floor(rand() * pool.length)) % pool.length];
    const low = text.includes("хотілося б") || text.includes("Єдине");
    day -= 3 + Math.floor(rand() * 20);
    const d = new Date(Date.UTC(2026, 0, 1) + day * 86_400_000);
    return {
      id: `${p.id}-r${i}`,
      author,
      city,
      date: `${d.getUTCDate()} ${months[d.getUTCMonth()]} ${d.getUTCFullYear()}`,
      rating: low ? 4 : rand() < p.rating - 4 ? 5 : 4,
      text,
      verified: rand() > 0.25,
    };
  });
}

/** Розподіл оцінок 5..1 так, щоб середнє було близьким до рейтингу товару */
export function ratingDistribution(p: Product) {
  const n = p.reviews;
  const five = Math.round(n * Math.min(0.95, Math.max(0.3, (p.rating - 4) * 0.9 + 0.1)));
  const four = Math.round((n - five) * 0.7);
  const three = Math.round((n - five - four) * 0.6);
  const two = Math.round((n - five - four - three) * 0.5);
  const one = n - five - four - three - two;
  return [five, four, three, two, one];
}

/* ---------- Схожі товари ---------- */

export function relatedProducts(list: Product[], p: Product, limit = 4) {
  const same = list.filter((x) => x.category === p.category && x.id !== p.id);
  // Спершу ті, що ближчі за ціною
  return same
    .sort((a, b) => Math.abs(a.price - p.price) - Math.abs(b.price - p.price))
    .slice(0, limit);
}
